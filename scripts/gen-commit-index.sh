#!/usr/bin/env bash
# Regenerate COMMITS.md — the exhaustive, grouped index of every commit
# in the repository, with a GitHub link on each. The curated narrative
# lives in CHANGELOG.md; this file is the raw audit trail the curated
# version summarises.
#
# Usage:
#   scripts/gen-commit-index.sh              # full history
#   scripts/gen-commit-index.sh <revrange>   # e.g. v0.1.0..HEAD
#
# The repository URL is read from `git remote get-url origin` and
# rewritten from the ssh form to https.
set -euo pipefail

RANGE="${1:-}"

REMOTE=$(git remote get-url origin 2>/dev/null || echo "")
# git@github.com-elcoosp:elcoosp/kod.git  ->  https://github.com/elcoosp/kod
# https://github.com/elcoosp/kod.git      ->  https://github.com/elcoosp/kod
WEB=$(printf '%s' "$REMOTE" \
    | sed -E 's#^git@[^:]+:#https://github.com/#' \
    | sed -E 's#^https?://github\.com/#https://github.com/#' \
    | sed -E 's#\.git$##')
if [ -z "$WEB" ]; then
    WEB=""
fi

OUT=COMMITS.md

# git log args: empty RANGE means all history. Word-split is safe here
# because RANGE is a single refspec the caller controls.
if [ -n "$RANGE" ]; then
    GITLOG=(git log "$RANGE")
else
    GITLOG=(git log)
fi

{
    printf '# Commit index\n\n'
    printf 'Auto-generated by `scripts/gen-commit-index.sh`. Do not edit by hand.\n\n'
    if [ -n "$RANGE" ]; then
        printf 'Range: `%s`\n\n' "$RANGE"
    fi
    printf 'The curated release narrative is [`CHANGELOG.md`](CHANGELOG.md); this\n'
    printf 'file is the exhaustive per-commit record behind it.\n\n'
    printf 'Regenerate with `just changelog` or `scripts/gen-commit-index.sh`.\n\n'

    TOTAL=$("${GITLOG[@]}" --format='%H' | wc -l | tr -d ' ')
    printf 'Total commits: **%s**.\n\n' "$TOTAL"

    for section in \
        "feat:Features" \
        "fix:Fixes" \
        "perf:Performance" \
        "refactor:Refactors" \
        "test:Tests" \
        "docs:Documentation" \
        "ci:CI" \
        "build:Build" \
        "deps:Dependencies" \
        "revert:Reverts"; do

        prefix="${section%%:*}"
        title="${section##*:}"

        # Count matches for this prefix. Match "prefix:",
        # "prefix(scope):", and "prefix!:".
        count=$(
            "${GITLOG[@]}" --format='%s' \
                | grep -cE "^${prefix}(\([^)]*\))?!?:" \
                || true
        )
        [ "$count" -eq 0 ] && continue

        printf '## %s\n\n' "$title"
        "${GITLOG[@]}" --format="%h %s" \
            | grep -E "^[0-9a-f]+ ${prefix}(\([^)]*\))?!?:" \
            | while IFS= read -r line; do
                sha="${line%% *}"
                subject="${line#* }"
                if [ -n "$WEB" ]; then
                    printf -- '- [`%s`](%s/commit/%s) %s\n' "$sha" "$WEB" "$sha" "$subject"
                else
                    printf -- '- `%s` %s\n' "$sha" "$subject"
                fi
            done
        printf '\n'
    done

    OTHER=$(
        "${GITLOG[@]}" --format='%s' \
            | grep -vcE '^(feat|fix|perf|refactor|test|docs|ci|build|deps|revert)(\([^)]*\))?!?:' \
            || true
    )
    if [ "$OTHER" -gt 0 ]; then
        printf '## Other\n\n'
        printf '%s commits (chores, styles, formatting, and non-conventional\n' "$OTHER"
        printf 'subjects) are omitted from this index. Run\n'
        printf '`git log --oneline %s` to see them.\n\n' "$RANGE"
    fi
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
